// BRAND.md: every rule of a client's brand as plain text, for any AI (ChatGPT, Claude, DeepSeek, Gemini, Cursor …).
const row = (...c) => `| ${c.join(' | ')} |`;

const brandMd = (x) => {
  const { cfg, p, themes, def, alt, core, pairs, type, fonts, fontUrl, radius, space, layout, labelFont } = x;
  const v = cfg.voice || {}, im = cfg.imagery || {}, idea = cfg.idea || {};
  const [setup, payoff] = idea.headline || [`${cfg.name}.`, 'On brand.'];
  const marker = { square: 'a 5px accent square', dot: 'a 6px accent dot', line: 'a 14px accent line', none: 'no marker' }[cfg.labelMarker || 'square'];
  const T = themes[def], U = themes[alt];
  const fontNames = [cfg.fonts.display.family, cfg.fonts.body.family, labelFont.family].filter((f, i, a) => a.indexOf(f) === i);
  return `# ${cfg.name} brand rules for AI

<!-- Generated by tools/brand-kit from brand.config.json. Do not edit by hand: change the config and rebuild. -->

You are making something for **${cfg.name}**${cfg.category ? `, ${cfg.category}` : ''}: a web page, a section, a social post, a deck, a document, an email or copy. Follow every rule in this file. When a request conflicts with these rules, follow the rules and say which rule you followed. When something is not covered, choose the plainest option that uses only the values listed here.

Brand version ${cfg.version || '1'}. Every value below is generated from the same token files the website uses, so these values are exact.

## 1. The idea

${idea.promise || ''}

Personality: ${idea.personality || ''}

${(idea.pillars || []).map((q) => `- **${q.title}.** ${q.body}`).join('\n')}

## 2. The rules that matter most

1. The default background is ${T.bg} (${def} theme). The ${alt} theme (${U.bg}) is for ${def === 'light' ? 'dark sections, night mode and social posts' : 'documents, proposals and print'}.
2. Text is ${T.text} on ${T.bg}, and ${U.text} on ${U.bg}. Secondary text uses the muted and faint roles below, never a new grey.
3. One accent: **${cfg.colors.accent.name} ${cfg.colors.accent.hex.toUpperCase()}**. Use it for the one primary button per view, links, the label marker, focus rings and small highlights. Never as a large background behind long text, never as a gradient.
4. Text and icons on the accent are always ${T['on-accent']}.
5. Accent-coloured text on ${T.bg} uses ${T['accent-text']}; on ${U.bg} it uses ${U['accent-text']}.
6. Fonts: **${cfg.fonts.display.family}** for headlines (display, H2, H3, big numbers). **${cfg.fonts.body.family}** for everything else.${labelFont.family !== cfg.fonts.body.family ? ` **${labelFont.family}** only for UPPERCASE labels.` : ''} No other fonts.
7. Headlines can be two-tone: the setup in the faint text colour, the payoff in full text colour. Example: “${setup} ${payoff}”
8. Sections start with an UPPERCASE label with ${marker} before it.
9. No emoji in headlines or buttons, no stock 3D, no AI-generated images of people.
10. Copy is short, exact and true. No invented numbers, testimonials or client logos.

## 3. Colour

### Palette

| Name | Hex | Use |
|---|---|---|
${core.map((c) => row(c.name, `\`${c.hex}\``, c.use || '')).join('\n')}

### Theme roles

Use the role, not the raw colour. In CSS each role is \`--${p}-<role>\`. The ${def} theme is the default; \`data-theme="${alt}"\` on any element switches it.

| Role | Light | Dark |
|---|---|---|
${Object.keys(themes.light).map((k) => row(`\`--${p}-${k}\``, themes.light[k], themes.dark[k])).join('\n')}

### Checked contrast (WCAG)

| Pair | Ratio | Result |
|---|---|---|
${pairs.map((q) => row(q.name, q.r.toFixed(2) + ':1', q.ok ? 'pass (AA)' : 'not for text: ' + q.use)).join('\n')}

Never: colours that are not in this file, gradients on text, pure #FFFFFF text on dark backgrounds unless it is listed above.

## 4. Type

Load: \`${fontUrl}\`

| Style | Size | Weight | Line height | Letter spacing | Font | Use |
|---|---|---|---|---|---|---|
${Object.entries(type).map(([k, [s, w, lh, ls, f, d]]) => row(k, s, w, lh, ls, { display: cfg.fonts.display.family, body: cfg.fonts.body.family, label: labelFont.family }[f], d)).join('\n')}

Sentence case everywhere except labels (UPPERCASE). Curly quotes and apostrophes. Leads about 40 characters wide, body about 70.

## 5. Layout, space and shape

${Object.entries(layout).map(([k, [val, d]]) => `- \`--${p}-${k}\`: ${val}. ${d}.`).join('\n')}
- Spacing scale: ${Object.values(space).join(', ')}.
- Radius: ${Object.entries(radius).map(([k, val]) => `${k} ${val}`).join(', ')}. Buttons and inputs use \`--${p}-radius-btn\`.
- Section pattern: label, headline, then a short lead to the right on desktop (\`.${p}-split\`), stacking under 900px. Hairlines between rows rather than boxes.

## 6. Components (website classes)

Wrap the page in \`<body class="${p}">\`, load \`brand/tokens.css\` then \`brand/components.css\`, then use:

| Class | What it is |
|---|---|
| \`.${p}-label\` | UPPERCASE eyebrow with the marker. \`.is-quiet\` drops the marker and dims it. |
| \`.${p}-display\`, \`.${p}-h2\`, \`.${p}-h3\`, \`.${p}-h4\`, \`.${p}-stat\` | Headlines. Wrap the setup in \`<span class="${p}-dim">\` for two-tone. |
| \`.${p}-lead\`, \`.${p}-body-lg\`, \`.${p}-small\`, \`.${p}-micro\` | Text sizes. |
| \`.${p}-btn.is-primary\` | Accent button. **One per view.** |
| \`.${p}-btn.is-solid\` | Text-colour button: the nav button, important secondary actions. |
| \`.${p}-btn.is-ghost\` | Outline button. \`.is-sm\` for the small size. |
| \`.${p}-link\` | Inline link with an accent underline. |
| \`.${p}-chip\`, \`.${p}-input\`, \`.${p}-error\` | Filters, inputs, error text. |
| \`.${p}-panel\`, \`.${p}-window\` + \`.${p}-window-bar\` | Panels and browser frames for screenshots. |
| \`.${p}-section\`, \`.${p}-container\`, \`.${p}-split\`, \`.${p}-frame\` | Layout. |

Buttons say what happens: “${v.ctaPrimary || 'Start'}”, “${v.ctaSecondary || 'See how it works'}”. Never “Click here” or “Learn more”.

Icons: 16px grid, 1.6px stroke, round caps, no fills, \`currentColor\`. Use the set in \`brand/icons/\` (${Object.keys(x.icons).length}: ${Object.keys(x.icons).join(', ')}).

## 7. Voice and copy

${v.summary || ''}

- **Words we use:** ${(v.use || []).join(', ')}.
- **Words we never use:** ${(v.avoid || []).join(', ')}.
- **Names:** ${v.names || cfg.name}

Write like this:
${(v.write || []).map((s) => `- “${s}”`).join('\n')}

Not like this:
${(v.not || []).map((s) => `- “${s}”`).join('\n')}

## 8. Logo

- Files: \`brand/logo-on-light.svg\`, \`brand/logo-on-dark.svg\`, \`brand/logo-mark.svg\` (square, for avatars and favicons).
- Always use the files. Clear space equal to the height of the first letter. Minimum width 72px.
- Never recolour it outside the palette, add effects, stretch it or set it in another font.
${x.logo.isText ? `- The logo is currently the word “${cfg.logo?.wordmark?.text || cfg.name}” set in ${cfg.fonts.display.family}. Outline it in a design tool before print.\n` : ''}
## 9. Imagery

${im.summary || ''}

Do:
${(im.do || []).map((s) => `- ${s}`).join('\n')}

Don’t:
${(im.dont || []).map((s) => `- ${s}`).join('\n')}

${im.photoPrompt ? `If you generate a photo with an image model, prompt for: “${im.photoPrompt}”. Never ask an image model for text or logos; set type afterwards.` : ''}

## 10. Recipes

### A web page or section

\`\`\`html
<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
  <link rel="stylesheet" href="${fontUrl}">
  <link rel="stylesheet" href="brand/tokens.css"><link rel="stylesheet" href="brand/components.css">
</head>
<body class="${p}">
  <section class="${p}-section">
    <div class="${p}-container ${p}-split">
      <div>
        <span class="${p}-label">Section label</span>
        <h2 class="${p}-h2"><span class="${p}-dim">${setup}</span> ${payoff}</h2>
      </div>
      <p class="${p}-lead">One or two plain sentences.</p>
    </div>
    <div class="${p}-container" style="margin-top:56px">
      <a class="${p}-btn is-primary" href="#">${v.ctaPrimary || 'Start'}</a>
      <a class="${p}-btn is-ghost" href="#">${v.ctaSecondary || 'See how it works'}</a>
    </div>
  </section>
</body>
</html>
\`\`\`

With Tailwind v4, import \`brand/tailwind-theme.css\` and use \`bg-${p}-bg text-${p}-text font-sans\`, \`font-display\` for headlines, \`bg-${p}-accent text-${p}-on-accent\`.

### Social posts

| Asset | Size |
|---|---|
| Feed post, carousel slide | 1080×1350 |
| Square post | 1080×1080 |
| Story, reel cover | 1080×1920 (keep the top 250px and bottom 340px clear) |
| Link preview (OG) | 1200×630 |
| LinkedIn banner | 1584×396 (text starts 30% from the left) |
| X header | 1500×500 |
| Avatar | 800×800, \`logo-mark.svg\` |
| YouTube thumbnail | 1280×720 |

Layout: 86px margin, label top left, two-tone headline in ${cfg.fonts.display.family} about 96px, logo bottom left, slide number bottom right. One idea per post. Carousels: cover, point, list, proof, call to action. Mix ${def} and ${alt} posts; the accent stays small. Captions: the first line is the headline, one link, at most three hashtags, alt text on every image.

### Decks and documents

Decks: one headline per slide, a label and slide number, lots of space, 16:9. Documents, proposals and invoices: the light theme (${themes.light.bg} page, ${themes.light.text} text), A4 or Letter, accent text in ${themes.light['accent-text']}.

## 11. CSS variables (paste-ready)

\`\`\`css
${x.tokensCss.trim()}
\`\`\`

## 12. Check before you hand it over

- [ ] Only colours from section 3, only the fonts in section 4.
- [ ] One accent primary button per view, with ${T['on-accent']} text on it.
- [ ] Sections start with a label; headlines follow the type scale.
- [ ] Text contrast at least 4.5:1 (use the pairs in section 3).
- [ ] Copy follows section 7; no banned words; every number is true.
- [ ] Works at 360px wide with no sideways scroll; respects reduced motion.

Run \`node ai/check-brand.mjs <file>\` on any HTML, CSS or SVG to catch off-brand colours, fonts, emoji and banned words.
`;
};

brandMd.prompt = (x) => {
  const { cfg, themes, def, alt, labelFont } = x;
  const T = themes[def], U = themes[alt], v = cfg.voice || {};
  return `You design and write for ${cfg.name}. Follow the attached BRAND.md exactly; it wins over any other style.
Essentials: ${def} theme by default, background ${T.bg}, text ${T.text}; ${alt} theme ${U.bg} with ${U.text} text. One accent, ${cfg.colors.accent.hex.toUpperCase()}, only for the single primary button per view, links, label markers and focus, with ${T['on-accent']} text on it. Accent text uses ${T['accent-text']} on ${T.bg}.
${cfg.fonts.display.family} for headlines, ${cfg.fonts.body.family} for everything else${labelFont.family !== cfg.fonts.body.family ? `, ${labelFont.family} for UPPERCASE labels` : ''}. No other fonts or colours. Every section opens with an UPPERCASE label.
Voice: ${(v.summary || '').replace(/\s+/g, ' ').slice(0, 220)} Never say: ${(v.avoid || []).slice(0, 8).join(', ')}.
No emoji in headlines, no AI-generated people, no invented numbers. Before answering, run the checklist in BRAND.md section 12.`;
};

export default brandMd;
